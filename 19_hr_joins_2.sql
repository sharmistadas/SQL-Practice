-- Q1. Display FIRST_NAME, LAST_NAME, DEPARTMENT_NAME.

SELECT E.FIRST_NAME,
       E.LAST_NAME,
       D.DEPARTMENT_NAME
FROM EMPLOYEES E
LEFT JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID;


-- Q2. Display FIRST_NAME, LAST_NAME, DEPARTMENT_NAME,
-- CITY, and COUNTRY_NAME.

SELECT E.FIRST_NAME,
       E.LAST_NAME,
       D.DEPARTMENT_NAME,
       L.CITY,
       C.COUNTRY_NAME
FROM EMPLOYEES E
LEFT JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
LEFT JOIN LOCATIONS L
ON D.LOCATION_ID = L.LOCATION_ID
LEFT JOIN COUNTRIES C
ON L.COUNTRY_ID = C.COUNTRY_ID;


-- Q3. Display employee LAST_NAME, current JOB_TITLE,
-- and current DEPARTMENT_NAME, sorted alphabetically
-- by department name.

SELECT E.LAST_NAME,
       J.JOB_TITLE,
       D.DEPARTMENT_NAME
FROM EMPLOYEES E
JOIN JOBS J
ON E.JOB_ID = J.JOB_ID
LEFT JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
ORDER BY D.DEPARTMENT_NAME ASC;


-- Q4. Display FIRST_NAME, JOB_TITLE, DEPARTMENT_NAME,
-- and CITY for employees in the Executive department.

SELECT E.FIRST_NAME,
       J.JOB_TITLE,
       D.DEPARTMENT_NAME,
       L.CITY
FROM EMPLOYEES E
JOIN JOBS J
ON E.JOB_ID = J.JOB_ID
JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN LOCATIONS L
ON D.LOCATION_ID = L.LOCATION_ID
WHERE D.DEPARTMENT_NAME = 'Executive';


-- Q5. Display DEPARTMENT_NAME, CITY, COUNTRY_NAME,
-- and REGION_NAME for departments outside the Americas.

SELECT D.DEPARTMENT_NAME,
       L.CITY,
       C.COUNTRY_NAME,
       R.REGION_NAME
FROM DEPARTMENTS D
JOIN LOCATIONS L
ON D.LOCATION_ID = L.LOCATION_ID
JOIN COUNTRIES C
ON L.COUNTRY_ID = C.COUNTRY_ID
JOIN REGIONS R
ON C.REGION_ID = R.REGION_ID
WHERE R.REGION_NAME <> 'Americas';


-- Q6. Display FIRST_NAME, JOB_TITLE, START_DATE, and
-- END_DATE from job history.

SELECT E.FIRST_NAME,
       J.JOB_TITLE,
       H.START_DATE,
       H.END_DATE
FROM JOB_HISTORY H
JOIN EMPLOYEES E
ON H.EMPLOYEE_ID = E.EMPLOYEE_ID
JOIN JOBS J
ON H.JOB_ID = J.JOB_ID;


-- Q7. Display FIRST_NAME, LAST_NAME, DEPARTMENT_NAME,
-- and STREET_ADDRESS for employees whose salary is
-- between 5000 and 12000.

SELECT E.FIRST_NAME,
       E.LAST_NAME,
       D.DEPARTMENT_NAME,
       L.STREET_ADDRESS
FROM EMPLOYEES E
JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN LOCATIONS L
ON D.LOCATION_ID = L.LOCATION_ID
WHERE E.SALARY BETWEEN 5000 AND 12000;


-- Q8. Display CITY, COUNTRY_NAME, and REGION_NAME for
-- all locations, including locations without departments.

SELECT L.CITY,
       C.COUNTRY_NAME,
       R.REGION_NAME
FROM LOCATIONS L
LEFT JOIN DEPARTMENTS D
ON L.LOCATION_ID = D.LOCATION_ID
JOIN COUNTRIES C
ON L.COUNTRY_ID = C.COUNTRY_ID
JOIN REGIONS R
ON C.REGION_ID = R.REGION_ID
GROUP BY L.LOCATION_ID,
         L.CITY,
         C.COUNTRY_NAME,
         R.REGION_NAME;


-- Q9. Display employee LAST_NAME, manager LAST_NAME,
-- and the employee's DEPARTMENT_NAME.

SELECT E.LAST_NAME AS EMPLOYEE_LAST_NAME,
       M.LAST_NAME AS MANAGER_LAST_NAME,
       D.DEPARTMENT_NAME
FROM EMPLOYEES E
LEFT JOIN EMPLOYEES M
ON E.MANAGER_ID = M.EMPLOYEE_ID
LEFT JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID;


-- Q10. Display DEPARTMENT_NAME, CITY, and the total
-- number of employees in each department-city combination,
-- sorted by city.

SELECT D.DEPARTMENT_NAME,
       L.CITY,
       COUNT(E.EMPLOYEE_ID) AS TOTAL_EMPLOYEES
FROM DEPARTMENTS D
JOIN LOCATIONS L
ON D.LOCATION_ID = L.LOCATION_ID
LEFT JOIN EMPLOYEES E
ON D.DEPARTMENT_ID = E.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_ID,
         D.DEPARTMENT_NAME,
         L.CITY
ORDER BY L.CITY ASC;


-- Q11. Display FIRST_NAME, LAST_NAME, current JOB_TITLE,
-- and previous JOB_TITLE for employees with job history.

SELECT E.FIRST_NAME,
       E.LAST_NAME,
       CJ.JOB_TITLE AS CURRENT_JOB_TITLE,
       PJ.JOB_TITLE AS PREVIOUS_JOB_TITLE
FROM EMPLOYEES E
JOIN JOB_HISTORY H
ON E.EMPLOYEE_ID = H.EMPLOYEE_ID
JOIN JOBS CJ
ON E.JOB_ID = CJ.JOB_ID
JOIN JOBS PJ
ON H.JOB_ID = PJ.JOB_ID;


-- Q12. Display JOB_TITLE, DEPARTMENT_NAME, and average
-- salary for each job in each department where average
-- salary is greater than 8000.

SELECT J.JOB_TITLE,
       D.DEPARTMENT_NAME,
       AVG(E.SALARY) AS AVERAGE_SALARY
FROM EMPLOYEES E
JOIN JOBS J
ON E.JOB_ID = J.JOB_ID
JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
GROUP BY J.JOB_ID,
         J.JOB_TITLE,
         D.DEPARTMENT_ID,
         D.DEPARTMENT_NAME
HAVING AVG(E.SALARY) > 8000;


-- Q13. Display FIRST_NAME, LAST_NAME, DEPARTMENT_NAME,
-- and COUNTRY_NAME for employees hired in 2005.

SELECT E.FIRST_NAME,
       E.LAST_NAME,
       D.DEPARTMENT_NAME,
       C.COUNTRY_NAME
FROM EMPLOYEES E
JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN LOCATIONS L
ON D.LOCATION_ID = L.LOCATION_ID
JOIN COUNTRIES C
ON L.COUNTRY_ID = C.COUNTRY_ID
WHERE E.HIRE_DATE >= DATE '2005-01-01'
  AND E.HIRE_DATE < DATE '2006-01-01';


-- Q14. Display COUNTRY_NAME, CITY, and DEPARTMENT_NAME
-- for all departments, including departments without employees.

SELECT DISTINCT C.COUNTRY_NAME,
                L.CITY,
                D.DEPARTMENT_NAME
FROM DEPARTMENTS D
JOIN LOCATIONS L
ON D.LOCATION_ID = L.LOCATION_ID
JOIN COUNTRIES C
ON L.COUNTRY_ID = C.COUNTRY_ID
LEFT JOIN EMPLOYEES E
ON D.DEPARTMENT_ID = E.DEPARTMENT_ID;


-- Q15. Display employee LAST_NAME, current DEPARTMENT_NAME,
-- and the LAST_NAME of the department's manager.

SELECT E.LAST_NAME AS EMPLOYEE_LAST_NAME,
       D.DEPARTMENT_NAME,
       M.LAST_NAME AS DEPARTMENT_MANAGER_LAST_NAME
FROM EMPLOYEES E
JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
LEFT JOIN EMPLOYEES M
ON D.MANAGER_ID = M.EMPLOYEE_ID;






