-- Q1. WAQTD DNAME of the employee whose name is SMITH
SELECT D.DNAME
FROM EMP E
JOIN DEPT D ON E.DEPTNO = D.DEPTNO
WHERE E.ENAME = 'SMITH';


-- Q2. WAQTD DNAME and LOC of the employee whose ENAME is KING
SELECT D.DNAME, D.LOC
FROM EMP E
JOIN DEPT D ON E.DEPTNO = D.DEPTNO
WHERE E.ENAME = 'KING';


