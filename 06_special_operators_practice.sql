
-- ==============================================
-- SQL SPECIAL OPERATORS PRACTICE 
-- TABLE: EMP (ORACLE SQL)
-- ==============================================

-- Q1. LIST ALL EMPLOYEES WHO DON'T HAVE A REPORTING MANAGER.
SELECT *
FROM EMP
WHERE MGR IS NULL;


-- Q2. LIST ALL SALESMEN IN DEPARTMENT 30.
SELECT *
FROM EMP
WHERE JOB = 'SALESMAN'
AND DEPTNO = 30;


-- Q3. LIST ALL SALESMEN IN DEPARTMENT 30
-- HAVING SALARY GREATER THAN 1500.
SELECT *
FROM EMP
WHERE JOB = 'SALESMAN'
AND DEPTNO = 30
AND SAL > 1500;


-- Q4. LIST ALL EMPLOYEES WHOSE NAME STARTS WITH S OR A.
SELECT *
FROM EMP
WHERE ENAME LIKE 'S%'
OR ENAME LIKE 'A%';


-- Q5. LIST ALL EMPLOYEES EXCEPT THOSE WORKING
-- IN DEPARTMENT 10 AND 20.
SELECT *
FROM EMP
WHERE DEPTNO NOT IN (10, 20);


-- Q6. LIST EMPLOYEES WHOSE NAME DOES NOT START WITH S.
SELECT *
FROM EMP
WHERE ENAME NOT LIKE 'S%';


-- Q7. LIST ALL EMPLOYEES HAVING REPORTING MANAGERS
-- IN DEPARTMENT 10.
SELECT *
FROM EMP
WHERE MGR IS NOT NULL
AND DEPTNO = 10;


-- Q8. LIST ALL EMPLOYEES WHOSE COMMISSION IS NULL
-- AND WHO ARE WORKING AS CLERKS.
SELECT *
FROM EMP
WHERE COMM IS NULL
AND JOB = 'CLERK';


-- Q9. LIST ALL EMPLOYEES WITHOUT A REPORTING MANAGER
-- IN DEPARTMENT 10 OR 30.
SELECT *
FROM EMP
WHERE MGR IS NULL
AND DEPTNO IN (10, 30);


-- Q10. LIST ALL SALESMEN IN DEPARTMENT 30
-- WITH SALARY GREATER THAN 2450.
SELECT *
FROM EMP
WHERE JOB = 'SALESMAN'
AND DEPTNO = 30
AND SAL > 2450;


-- Q11. LIST ALL ANALYSTS IN DEPARTMENT 20
-- HAVING SALARY GREATER THAN 2500.
SELECT *
FROM EMP
WHERE JOB = 'ANALYST'
AND DEPTNO = 20
AND SAL > 2500;


-- Q12. LIST ALL EMPLOYEES WHOSE NAME STARTS WITH M OR J.
SELECT *
FROM EMP
WHERE ENAME LIKE 'M%'
OR ENAME LIKE 'J%';


-- Q13. LIST ALL EMPLOYEES WITH ANNUAL SALARY,
-- EXCEPT THOSE WORKING IN DEPARTMENT 30.
SELECT EMP.*, SAL * 12 AS ANNUAL_SALARY
FROM EMP
WHERE DEPTNO <> 30;


-- Q14. LIST EMPLOYEES WHOSE NAME DOES NOT END
-- WITH ES OR R.
SELECT *
FROM EMP
WHERE ENAME NOT LIKE '%ES'
AND ENAME NOT LIKE '%R';


-- Q15. LIST EMPLOYEES HAVING REPORTING MANAGERS
-- IN DEPARTMENT 10, ALONG WITH A 10% SALARY HIKE.
SELECT EMP.*, SAL * 1.10 AS HIKE_SALARY
FROM EMP
WHERE MGR IS NOT NULL
AND DEPTNO = 10;


-- Q16. DISPLAY SALESMEN HAVING E AS THE LAST-BUT-ONE
-- CHARACTER IN ENAME AND SALARY WITH EXACTLY 4 DIGITS.
SELECT *
FROM EMP
WHERE JOB = 'SALESMAN'
AND ENAME LIKE '%E_'
AND LENGTH(TO_CHAR(TRUNC(ABS(SAL)))) = 4;


-- Q17. DISPLAY EMPLOYEES WHO JOINED AFTER YEAR 1981.
SELECT *
FROM EMP
WHERE HIREDATE >= DATE '1982-01-01';


-- Q18. DISPLAY EMPLOYEES WHO JOINED IN FEBRUARY.
SELECT *
FROM EMP
WHERE TO_CHAR(HIREDATE, 'MM') = '02';


-- Q19. LIST EMPLOYEES WHO ARE NOT WORKING AS MANAGERS
-- OR CLERKS, IN DEPARTMENT 10 OR 20,
-- WITH SALARY BETWEEN 1000 AND 3000.
SELECT *
FROM EMP
WHERE JOB NOT IN ('MANAGER', 'CLERK')
AND DEPTNO IN (10, 20)
AND SAL BETWEEN 1000 AND 3000;


-- ==============================================
-- OVERALL EXPLANATION
-- ==============================================

-- MGR IS NULL
-- Finds employees who do not have a reporting manager.

-- MGR IS NOT NULL
-- Finds employees who have a reporting manager.

-- IN (10, 20)
-- Matches department 10 or department 20.

-- NOT IN (10, 20)
-- Excludes department 10 and department 20.

-- LIKE 'S%'
-- Name starts with S.

-- LIKE '%E_'
-- E is the second-last character of the name.

-- NOT LIKE '%ES'
-- Name does not end with ES.

-- NOT LIKE '%R'
-- Name does not end with R.

-- COMM IS NULL
-- Commission has no recorded value.

-- SAL * 12
-- Calculates annual salary.

-- SAL * 1.10
-- Calculates salary after a 10% hike.

-- BETWEEN 1000 AND 3000
-- Includes both 1000 and 3000.

-- TO_CHAR(HIREDATE, 'MM')
-- Extracts the month number from the hire date.

-- LENGTH()
-- Counts the number of characters.

-- TO_CHAR()
-- Converts a numeric value into text.

-- TRUNC()
-- Removes the decimal part.

-- ABS()
-- Returns the absolute value.

-- NOTE:
-- These queries use Oracle SQL and the standard EMP table.
-- Q16 treats salary as a 4-digit whole-number amount.
-- Q18 finds employees hired in February of any year.
